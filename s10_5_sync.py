def extract_main_name(col2_text):
    t = col2_text
    # 移除首个☆（可能跟随空格）
    t = t.replace("☆", "", 1)
    # 找到第一个 " " + 队伍token 或 队伍token 的位置
    best = len(t)
    for tok in TEAM_TOKENS:
        idx = t.find(tok)
        if idx != -1 and idx < best:
            best = idx
    name = t[:best]
    # 去掉前后空格
    return name.strip()

# 规范化主名：去掉空白，用于宽松匹配
def norm(s):
    return "".join(ch for ch in s if not ch.isspace())

# ---------------- 解析网页开条列 ----------------
# 开条列格式: "开条×2下次6000" 或 "开条×2违规×1下次8000" 或 "下次2000"(0次)
# next_amt 直接取网页"下次XXXXX"金额（最权威，含违规影响）。
# fail_times 反推：令 下次金额 = 开条次数*2000+2000 严格成立，即 fail_times = (next_amt-2000)//2000。
# 对普通记录该值与网页"开条×N"一致；对含违规记录（如开条×2违规×1下次8000）则为3，保证公式与金额自洽。
def parse_open(open_col):
    open_col = norm(open_col)
    m_next = re.search(r'下次(\d+)', open_col)
    next_amt = int(m_next.group(1)) if m_next else 0
    fail_times = (next_amt - 2000) // 2000 if next_amt else 0
    return fail_times, next_amt

